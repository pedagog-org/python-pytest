"""Run the failure corpus and write corpus/REPORT.md: for each case, what the
student sees today (`error`, pytest's default report), the same with
--tb=short and --tb=line, and the short description the helper already
computes (describe_failure, plus failed checks'). In-process (no isolation).
    python scripts/failure-corpus.py
    python scripts/failure-corpus.py --from results.json [broken-results.json]
"""

import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"

SPY = '''
import json, os, pytest
@pytest.hookimpl(trylast=True)
def pytest_sessionfinish(session):
    rec = session.config.pluginmanager.get_plugin("pedagog-results")
    out = {}
    for node, e in rec.entries.items():
        out[node] = {"failure": e.failure, "checks": [f for s in e.scores for f in s.failures]}
    with open(os.environ["SPY_OUT"], "w") as f:
        json.dump(out, f)
'''


def run(student: Path, tb: str) -> tuple[dict, dict]:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "spy.py").write_text(SPY)
        out, spy = tmp / "results.yaml", tmp / "spy.json"
        env = {**os.environ, "PYTHONPATH": f"{student}{os.pathsep}{tmp}", "SPY_OUT": str(spy)}
        subprocess.run(
            [sys.executable, "-m", "pytest", str(CORPUS / "tests"), "--rootdir", str(CORPUS / "tests"),
             "-p", "no:cacheprovider", "-p", "spy", "--pedagog-results", str(out), f"--tb={tb}", "-q"],
            env=env, cwd=tmp, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        results = json.loads(out.read_text())
        found = json.loads(spy.read_text()) if spy.exists() else {}
        return results, found


def block(text: str) -> str:
    return "```\n" + (text.rstrip() or "(empty)") + "\n```\n"


def from_results(results: Path, broken: Path | None) -> None:
    """corpus/REPORT-isolated.md from a real grading's results (the corpus graded on
    a cluster under process isolation), and optionally the broken file's run."""
    r = json.loads(results.read_text())
    lines = ["# Failure corpus, graded under process isolation\n",
             "From a real grading run (validation of the corpus as an assignment). `error` as",
             "students would see it today, and the trace's status line (what `describe_failure`",
             "made of it).\n"]
    for t in r["tests"]:
        lines.append(f"## {t['name']}\n")
        lines.append(f"`{t['node']}` · status `{t['status']}` · {len(t['error'].splitlines())} lines of `error`\n")
        lines.append("**Computed short description** (from the trace):\n")
        lines.append(block(t["trace"].splitlines()[-1].strip().removeprefix("status: ")))
        lines.append("**`error-sanitized`** (what students get):\n")
        lines.append(block(t.get("error-sanitized", "")))
        lines.append("**`error`** (staff):\n")
        lines.append(block(t["error"]))
    if broken is not None:
        b = json.loads(broken.read_text())
        lines.append("## 11. A syntax error in the student's file\n")
        lines.append(f"`run.status` `{b['run']['status']}`; `run.output`:\n")
        lines.append(block(b["run"]["output"]))
    (CORPUS / "REPORT-isolated.md").write_text("\n".join(lines))
    print(CORPUS / "REPORT-isolated.md")


def main() -> None:
    modes = {tb: run(CORPUS / "student", tb) for tb in ["long", "short", "line"]}
    long_results, spy = modes["long"]
    lines = ["# Failure corpus\n",
             "Generated by `scripts/failure-corpus.py` (in-process, no isolation). For each case: the short",
             "description the helper already computes, then `error` as students see it today (pytest's",
             "default report), then with `--tb=short` and `--tb=line`.\n"]
    for i, t in enumerate(long_results["tests"]):
        node = t["node"]
        doc = next((ln.strip() for ln in (t["name"] or "").splitlines()), node)
        lines.append(f"## {t['name']}\n")
        lines.append(f"`{node}` · status `{t['status']}` · {len(t['error'].splitlines())} lines of `error`\n")
        s = spy.get(node, {})
        lines.append("**Computed short description** (`describe_failure`, failed checks first):\n")
        lines.append(block("\n".join([*s.get("checks", []), *([s["failure"]] if s.get("failure") else [])])))
        lines.append("**`error-sanitized`** (what students get):\n")
        lines.append(block(t.get("error-sanitized", "")))
        lines.append("**`error`** (`--tb=long`, the default; staff):\n")
        lines.append(block(t["error"]))
        for tb in ["short", "line"]:
            other = next(x for x in modes[tb][0]["tests"] if x["node"] == node)
            lines.append(f"**`error` with `--tb={tb}`:**\n")
            lines.append(block(other["error"]))
    broken, _ = run(CORPUS / "broken", "long")
    lines.append("## 11. A syntax error in the student's file\n")
    lines.append(f"The whole run is an error (`run.status` `{broken['run']['status']}`).\n")
    lines.append("**`run.output-sanitized`** (what students get):\n")
    lines.append(block(broken["run"].get("output-sanitized", "")))
    lines.append("**`run.output`** (staff):\n")
    lines.append(block(broken["run"]["output"]))
    (CORPUS / "REPORT.md").write_text("\n".join(lines))
    print(CORPUS / "REPORT.md")


if __name__ == "__main__":
    # --from RESULTS [BROKEN]: format a real grading's results instead of running.
    if len(sys.argv) > 2 and sys.argv[1] == "--from":
        from_results(Path(sys.argv[2]), Path(sys.argv[3]) if len(sys.argv) > 3 else None)
    else:
        main()
